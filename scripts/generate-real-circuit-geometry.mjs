import { writeFile } from 'node:fs/promises';

const f1Source = 'https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson';
const extendedSource = 'https://raw.githubusercontent.com/GameDev-Toolkit/global-motorsport-circuits-json/main';

const f1Circuits = [
  { key: 'spa', id: 'be-1925', length: 7004, clockwise: true },
  { key: 'monaco', id: 'mc-1929', length: 3337, clockwise: true },
  { key: 'suzuka', id: 'jp-1962', length: 5807, clockwise: true },
  { key: 'monza', id: 'it-1922', length: 5793, clockwise: true },
  { key: 'interlagos', id: 'br-1940', length: 4309, clockwise: false },
  { key: 'hungaroring', id: 'hu-1986', length: 4381, clockwise: true }
];

function distance(a, b) {
  return Math.hypot(b[0] - a[0], b[1] - a[1]);
}

function closedLength(points) {
  let total = 0;
  for (let i = 0; i < points.length; i++) total += distance(points[i], points[(i + 1) % points.length]);
  return total;
}

function signedArea(points) {
  let area = 0;
  for (let i = 0; i < points.length; i++) {
    const a = points[i];
    const b = points[(i + 1) % points.length];
    area += a[0] * b[1] - b[0] * a[1];
  }
  return area / 2;
}

function simplifyOpen(points, tolerance) {
  if (points.length <= 2) return points;
  const start = points[0];
  const end = points.at(-1);
  const dx = end[0] - start[0];
  const dy = end[1] - start[1];
  const lengthSq = dx * dx + dy * dy;
  let greatest = tolerance;
  let split = -1;
  for (let i = 1; i < points.length - 1; i++) {
    const p = points[i];
    const t = lengthSq ? Math.max(0, Math.min(1, ((p[0] - start[0]) * dx + (p[1] - start[1]) * dy) / lengthSq)) : 0;
    const error = distance(p, [start[0] + t * dx, start[1] + t * dy]);
    if (error > greatest) {
      greatest = error;
      split = i;
    }
  }
  if (split < 0) return [start, end];
  return [
    ...simplifyOpen(points.slice(0, split + 1), tolerance).slice(0, -1),
    ...simplifyOpen(points.slice(split), tolerance)
  ];
}

function simplifyClosed(points, tolerance) {
  if (points.length <= 12) return points;
  let farthest = 1;
  let farthestDistance = 0;
  for (let i = 1; i < points.length; i++) {
    const d = distance(points[0], points[i]);
    if (d > farthestDistance) {
      farthestDistance = d;
      farthest = i;
    }
  }
  const firstHalf = simplifyOpen(points.slice(0, farthest + 1), tolerance);
  const secondHalf = simplifyOpen([...points.slice(farthest), points[0]], tolerance);
  const result = [...firstHalf.slice(0, -1), ...secondHalf.slice(0, -1)];
  return result.length >= 8 ? result : points;
}

function normalize(points, lengthMeters, clockwise, tolerance) {
  let result = points.map(([x, y]) => [Number(x), Number(y)]);
  while (result.length > 3 && distance(result[0], result.at(-1)) < 1e-5) result.pop();

  const isClockwise = signedArea(result) < 0;
  if (isClockwise !== clockwise) result.reverse();

  result = simplifyClosed(result, tolerance);
  const perimeter = closedLength(result);
  const scale = lengthMeters / perimeter;
  const center = result.reduce((sum, p) => [sum[0] + p[0] / result.length, sum[1] + p[1] / result.length], [0, 0]);
  return result.map(([x, y]) => [
    Math.round((x - center[0]) * scale * 10) / 10,
    Math.round((y - center[1]) * scale * 10) / 10
  ]);
}

const f1Response = await fetch(f1Source);
if (!f1Response.ok) throw new Error(`F1 geometry source failed: ${f1Response.status}`);
const f1 = await f1Response.json();
const generated = {};
for (const circuit of f1Circuits) {
  const feature = f1.features.find((item) => item.properties.id === circuit.id);
  if (!feature) throw new Error(`Missing F1 geometry: ${circuit.id}`);
  const coordinates = feature.geometry.coordinates;
  const latitude = coordinates.reduce((sum, point) => sum + point[1] / coordinates.length, 0);
  const originLon = coordinates.reduce((sum, point) => sum + point[0] / coordinates.length, 0);
  const projected = coordinates.map(([lon, lat]) => [
    (lon - originLon) * 111320 * Math.cos(latitude * Math.PI / 180),
    (lat - latitude) * 110574
  ]);
  generated[circuit.key] = normalize(projected, circuit.length, circuit.clockwise, 8);
}

const extendedCircuits = [
  { key: 'bathurst', file: 'other/mount_panorama_circuit.json', length: 6213, clockwise: false, tolerance: 8 },
  { key: 'charlotteRoval', file: 'wec/charlotte_motor_speedway.json', length: 3669, clockwise: true, tolerance: 4 }
];

for (const circuit of extendedCircuits) {
  const response = await fetch(`${extendedSource}/${circuit.file}`);
  if (!response.ok) throw new Error(`Extended geometry source failed (${circuit.file}): ${response.status}`);
  const data = await response.json();
  generated[circuit.key] = normalize(data.points.map((point) => [point.x, point.y]), circuit.length, circuit.clockwise, circuit.tolerance);
}

const sourceHeader = `// Generated by scripts/generate-real-circuit-geometry.mjs.\n// F1 circuit coordinates: bacinger/f1-circuits (MIT), from public map references.\n// Bathurst and Charlotte Roval coordinates: GameDev-Toolkit/global-motorsport-circuits-json (Apache-2.0).\n// Geometry is simplified and scaled to published lap length; elevation is not included in these source paths.\n`;
const entries = Object.entries(generated).map(([key, points]) =>
  `  ${key}: [\n${points.map(([x, y]) => `    [${x}, ${y}]`).join(',\n')}\n  ]`
);
const output = `${sourceHeader}\nexport type CircuitCoordinate = readonly [number, number];\n\nexport const REAL_CIRCUIT_GEOMETRY = {\n${entries.join(',\n')}\n} as const satisfies Record<string, readonly CircuitCoordinate[]>;\n`;
await writeFile(new URL('../src/utils/realCircuitGeometry.ts', import.meta.url), output);
